// Writes a content hash of the built .wasm to wasm/pkg/build_hash.{js,d.ts}.
// The app requests `findev_wasm_bg.wasm?v=<hash>`, so a changed module always
// gets a new URL and browsers never pair new code with an old cached .wasm.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const pkg = fileURLToPath(new URL('../wasm/pkg/', import.meta.url));
const hash = createHash('sha256')
  .update(readFileSync(`${pkg}findev_wasm_bg.wasm`))
  .digest('hex')
  .slice(0, 16);

const header = '// Generated by scripts/wasm-hash.mjs — do not edit.\n';
writeFileSync(`${pkg}build_hash.js`, `${header}export const WASM_HASH = '${hash}';\n`);
writeFileSync(`${pkg}build_hash.d.ts`, `${header}export declare const WASM_HASH: string;\n`);
console.log(`wasm hash: ${hash}`);
